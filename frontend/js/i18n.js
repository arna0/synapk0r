// Strings with numbers inside
const KK_PATTERNS = [
  [/^Пройдено (\d+) из (\d+)$/, (m) => `${m[2]} ішінен ${m[1]} өтілді`],
  [/^(\d+) сек$/, (m) => `${m[1]} сек`]
];

const DICTS = { kk: KK, en: typeof EN !== 'undefined' ? EN : {} };
const PATTERNS = { kk: KK_PATTERNS, en: typeof EN_PATTERNS !== 'undefined' ? EN_PATTERNS : [] };
const LANGS = ['ru', 'kk', 'en'];

let currentLang = 'ru';

// Translation of one Russian string in the current language (used by patterns and canvas text)
function trRu(ru) {
  const dict = DICTS[currentLang];
  return (dict && dict[ru]) || ru;
}

// Text drawn onto 3D canvases (signs, patient record, monitoring screen) never reaches the DOM,
// so translate it at draw time. Scenes are built after the language is chosen.
if (typeof CanvasRenderingContext2D !== 'undefined') {
  const drawText = CanvasRenderingContext2D.prototype.fillText;
  CanvasRenderingContext2D.prototype.fillText = function (text, ...rest) {
    if (currentLang !== 'ru' && typeof text === 'string' && /[А-Яа-яЁё]/.test(text)) text = translateString(text) ?? text;
    return drawText.call(this, text, ...rest);
  };
}
const originalText = new WeakMap();

function translateString(ru) {
  const dict = DICTS[currentLang];
  if (!dict) return null;
  const trimmed = ru.trim();
  if (!trimmed) return null;
  if (dict[trimmed]) return ru.replace(trimmed, dict[trimmed]);
  // same text with different spacing (canvas labels use double spaces as separators)
  const squashed = trimmed.replace(/\s+/g, ' ');
  if (squashed !== trimmed && dict[squashed]) return dict[squashed].replace(/ (\d) /g, '  $1 ');
  // leading emoji, bullets, icons: "🔄 Повторить симуляцию", "• Компетенция"
  const m = trimmed.match(/^([^A-Za-zА-Яа-яЁёӘәҒғҚқҢңӨөҰұҮүҺһІі0-9]+)(.+)$/u);
  if (m && dict[m[2].trim()]) return ru.replace(m[2].trim(), dict[m[2].trim()]);
  for (const [re, fn] of PATTERNS[currentLang]) {
    const mm = trimmed.match(re);
    if (mm) return ru.replace(trimmed, fn(mm));
  }
  return null;
}

function translateNode(node) {
  if (node.nodeType === Node.TEXT_NODE) {
    const saved = originalText.get(node);
    // if the page changed this text since we translated it, treat the new value as Russian
    const source = saved && node.nodeValue === saved.out ? saved.ru : node.nodeValue;
    if (currentLang !== 'ru') {
      const out = translateString(source);
      if (out !== null && out !== node.nodeValue) {
        originalText.set(node, { ru: source, out });
        node.nodeValue = out;
      } else if (out === null && saved && node.nodeValue === saved.out) {
        node.nodeValue = saved.ru;
        originalText.delete(node);
      }
    } else if (saved && node.nodeValue === saved.out) {
      node.nodeValue = saved.ru;
      originalText.delete(node);
    }
    return;
  }
  if (node.nodeType !== Node.ELEMENT_NODE || node.tagName === 'SCRIPT' || node.tagName === 'STYLE') return;
  if (node.title && /[А-Яа-яЁё]/.test(node.dataset.ruTitle || node.title)) {
    if (!node.dataset.ruTitle) node.dataset.ruTitle = node.title;
    node.title = currentLang === 'ru' ? node.dataset.ruTitle : (translateString(node.dataset.ruTitle) ?? node.dataset.ruTitle);
  }
  if (node.placeholder) {
    if (!node.dataset.ruPlaceholder) node.dataset.ruPlaceholder = node.placeholder;
    const ru = node.dataset.ruPlaceholder;
    const dict = DICTS[currentLang];
    node.placeholder = dict && dict[ru] ? dict[ru] : ru;
  }
  node.childNodes.forEach(translateNode);
}

function translateRoots() {
  I18N_ROOTS.forEach(sel => { const el = document.querySelector(sel); if (el) translateNode(el); });
}

function setLanguage(lang) {
  currentLang = LANGS.includes(lang) ? lang : 'ru';
  try { localStorage.setItem(I18N_KEY, currentLang); } catch (e) {}
  document.documentElement.lang = currentLang;
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === currentLang));
  translateRoots();
  const html = document.documentElement;
  if (!html.dataset.ruTitle) html.dataset.ruTitle = document.title;
  document.title = currentLang === 'ru' ? html.dataset.ruTitle : trRu(html.dataset.ruTitle);
}

function getLanguage() { return currentLang; }

window.addEventListener('DOMContentLoaded', () => {
  let lang = new URLSearchParams(location.search).get('lang');
  if (!lang) { try { lang = localStorage.getItem(I18N_KEY); } catch (e) {} }
  // Content rendered later (intro, report, career block, survey) is translated as it appears
  const observer = new MutationObserver(records => {
    if (currentLang === 'ru') return;
    records.forEach(r => {
      const inRoot = I18N_ROOTS.some(sel => { const root = document.querySelector(sel); return root && root.contains(r.target); });
      if (!inRoot) return;
      if (r.type === 'characterData') translateNode(r.target);
      else r.addedNodes.forEach(translateNode);
    });
  });
  observer.observe(document.body, { subtree: true, childList: true, characterData: true });
  setLanguage(lang || 'ru');
});

window.setLanguage = setLanguage;
window.getLanguage = getLanguage;
